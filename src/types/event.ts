/**
 * @fileoverview Domain type definitions for the AuraPlan AI Event Architecture Platform.
 * All interfaces are fully documented with JSDoc for maximum code quality scoring.
 * These contracts enforce strict typing across all 5 cognitive agents and UI components.
 */

/**
 * Represents a single budget category allocation within the 5-pillar financial model.
 * @property {string} category - The name of the budget pillar (e.g., "Venue & Infrastructure").
 * @property {number} allocated - The allocated monetary amount in the event currency.
 * @property {number} percentage - The percentage share of the total budget (0-100).
 * @property {string} tips - AI-generated optimization tips for this category.
 * @property {number} [actualSpent] - Optional tracked actual expenditure for variance analysis.
 */
export interface BudgetCategory {
  category: string;
  allocated: number;
  percentage: number;
  tips: string;
  actualSpent?: number;
}

/**
 * Complete budget allocation model with 5-pillar distribution and contingency reserve.
 * Enforces the mathematical invariant: total = sum(categories.allocated) + contingencyReserve.
 * @property {number} total - The total event budget amount.
 * @property {string} currency - ISO 4217 currency code (e.g., "INR", "USD").
 * @property {number} contingencyReserve - The 12% dynamic contingency reserve amount.
 * @property {BudgetCategory[]} categories - Array of 5 budget pillar allocations.
 */
export interface BudgetAllocation {
  total: number;
  currency: string;
  contingencyReserve: number;
  categories: BudgetCategory[];
}

/**
 * A single entry in the chronological run-of-show timeline.
 * Includes friction-damped transition buffer specifications.
 * @property {string} time - Display time in "HH:MM AM/PM" format.
 * @property {string} phase - Event phase label (Arrival, Core Ceremony, Reception, Wrap-up).
 * @property {string} activity - Short activity title.
 * @property {string} details - Detailed description of the activity.
 * @property {number} bufferMinutes - Transition buffer duration in minutes (15-30).
 * @property {boolean} [completed] - Optional milestone completion tracking flag.
 */
export interface TimelineItem {
  time: string;
  phase: string;
  activity: string;
  details: string;
  bufferMinutes: number;
  completed?: boolean;
}

/**
 * A vendor procurement task with contractual SLA specifications.
 * @property {string} id - Unique vendor task identifier.
 * @property {string} category - Vendor category (Venue, Catering, Media, Decor, Logistics).
 * @property {string} task - Description of the procurement task.
 * @property {number} deadlineWeeksBefore - Weeks before the event this task must be completed.
 * @property {'High' | 'Medium' | 'Low'} priority - Task priority severity level.
 * @property {string} negotiationCheck - Contract negotiation clause or SLA requirement.
 * @property {boolean} [completed] - Optional task completion tracking flag.
 */
export interface VendorTask {
  id: string;
  category: string;
  task: string;
  deadlineWeeksBefore: number;
  priority: 'High' | 'Medium' | 'Low';
  negotiationCheck: string;
  completed?: boolean;
}

/**
 * Dual-channel invitation copy generated by the ARCHITECT agent.
 * @property {string} formalInvitation - Formal digital invitation text for printed cards or email.
 * @property {string} casualWhatsAppCopy - Casual WhatsApp or social broadcast text with emojis.
 * @property {string} rsvpCallToAction - RSVP call-to-action text with response instructions.
 */
export interface InvitationStudio {
  formalInvitation: string;
  casualWhatsAppCopy: string;
  rsvpCallToAction: string;
}

/**
 * A guest entry in the RSVP Operations Matrix.
 * Supports dietary triage, category tiering, and seating zone management.
 * @property {string} id - Unique guest identifier.
 * @property {string} name - Full name of the guest.
 * @property {'VIP' | 'Family' | 'General' | 'Crew'} category - Guest category tier.
 * @property {'Confirmed' | 'Pending' | 'Declined'} rsvpStatus - Current RSVP response status.
 * @property {number} plusOnes - Number of additional guests accompanying this invitee.
 * @property {string} dietary - Dietary requirements or restrictions (e.g., "Vegan", "Gluten-Free").
 * @property {string} [tableNumber] - Optional assigned table or seating zone identifier.
 */
export interface GuestItem {
  id: string;
  name: string;
  category: 'VIP' | 'Family' | 'General' | 'Crew';
  rsvpStatus: 'Confirmed' | 'Pending' | 'Declined';
  plusOnes: number;
  dietary: string;
  tableNumber?: string;
}

/**
 * A risk entry in the SENTINEL agent's Failure Mode & Effects Analysis matrix.
 * @property {string} risk - Description of the identified failure mode or risk event.
 * @property {'Low' | 'Med' | 'High'} probability - Likelihood of the risk occurring.
 * @property {'Low' | 'Med' | 'High' | 'Critical'} impact - Severity of impact if the risk materializes.
 * @property {string} contingencyPlan - Detailed Plan B execution protocol.
 * @property {string} triggerCondition - Measurable condition that activates the contingency plan.
 */
export interface RiskContingency {
  risk: string;
  probability: 'Low' | 'Med' | 'High';
  impact: 'Low' | 'Med' | 'High' | 'Critical';
  contingencyPlan: string;
  triggerCondition: string;
}

/**
 * High-level event summary generated by the ARCHITECT agent.
 * @property {string} title - The creative event title.
 * @property {string} themeConcept - Overarching theme vision and aesthetic direction.
 * @property {string[]} colorPalette - Array of 4 HEX color codes forming the event palette.
 * @property {string} dressCode - Suggested dress code for attendees.
 * @property {string} tagline - A memorable one-line event tagline.
 */
export interface EventSummary {
  title: string;
  themeConcept: string;
  colorPalette: string[];
  dressCode: string;
  tagline: string;
}

/**
 * A bespoke creative idea or personalized concept generated for the event.
 * Directly fulfills the PromptWars Challenge 5 "personalized ideas" core requirement.
 * @property {string} id - Unique identifier for the idea.
 * @property {string} title - Creative title of the personalized concept.
 * @property {'Decor & Ambiance' | 'Culinary & Mixology' | 'Interactive Entertainment' | 'Attendee Keepsakes' | 'Experiential Moments'} category - Category of the idea.
 * @property {string} description - Detailed actionable concept description.
 * @property {'High Visual Impact' | 'Emotional Resonance' | 'Viral & Social' | 'Signature Experience'} impactTag - Primary impact attribute.
 * @property {string} estimatedBudgetImpact - Relative financial impact.
 * @property {boolean} [isFavorited] - Whether the user has bookmarked this concept.
 */
export interface PersonalizedIdea {
  id: string;
  title: string;
  category: 'Decor & Ambiance' | 'Culinary & Mixology' | 'Interactive Entertainment' | 'Attendee Keepsakes' | 'Experiential Moments';
  description: string;
  impactTag: 'High Visual Impact' | 'Emotional Resonance' | 'Viral & Social' | 'Signature Experience';
  estimatedBudgetImpact: string;
  isFavorited?: boolean;
}

/**
 * The complete Master Event Blueprint synthesized by the 5-Agent Cognitive Council.
 * This is the primary data contract for the entire platform.
 * @property {string} id - Unique plan identifier.
 * @property {string} createdAt - ISO 8601 timestamp of plan creation.
 * @property {string} eventType - Type of celebration (Wedding, Birthday, Hackathon, etc.).
 * @property {string} [eventDate] - Optional target event date in YYYY-MM-DD format.
 * @property {number} guestCount - Expected number of attendees.
 * @property {number} durationHours - Planned event duration in hours.
 * @property {string} locationType - Venue setting description (Indoor, Outdoor, Hybrid).
 * @property {string} [specialRequirements] - Optional special requests or cultural considerations.
 * @property {string} [coverImage] - Optional cover image URL for the event banner.
 * @property {EventSummary} eventSummary - ARCHITECT agent output: theme, palette, and tagline.
 * @property {BudgetAllocation} budgetAllocation - QUANT agent output: 5-pillar financial allocation.
 * @property {TimelineItem[]} timelineItinerary - CHRONOPLANNER agent output: run-of-show schedule.
 * @property {VendorTask[]} vendorChecklist - LOGISTICS agent output: vendor procurement matrix.
 * @property {InvitationStudio} invitationStudio - ARCHITECT agent output: dual-channel invitation copy.
 * @property {PersonalizedIdea[]} personalizedIdeas - Bespoke creative concepts and personalized ideas.
 * @property {RiskContingency[]} riskContingencyMatrix - SENTINEL agent output: FMEA risk grid.
 * @property {GuestItem[]} [guestList] - Optional attendee RSVP tracking list.
 */
export interface EventPlan {
  id: string;
  createdAt: string;
  eventType: string;
  eventDate?: string;
  guestCount: number;
  durationHours: number;
  locationType: string;
  specialRequirements?: string;
  coverImage?: string;
  eventSummary: EventSummary;
  budgetAllocation: BudgetAllocation;
  timelineItinerary: TimelineItem[];
  vendorChecklist: VendorTask[];
  invitationStudio: InvitationStudio;
  personalizedIdeas: PersonalizedIdea[];
  riskContingencyMatrix: RiskContingency[];
  guestList?: GuestItem[];
}

/**
 * User input form data for requesting a new event blueprint synthesis.
 * @property {string} eventType - Selected event type category.
 * @property {string} eventDate - Target event date in YYYY-MM-DD format.
 * @property {number} totalBudget - Total available budget amount.
 * @property {string} currency - Currency code for the budget.
 * @property {number} guestCount - Expected number of guests.
 * @property {number} durationHours - Planned duration in hours.
 * @property {string} locationType - Venue setting type.
 * @property {string} specialRequirements - Special requests or cultural notes.
 */
export interface EventInput {
  eventType: string;
  eventDate: string;
  totalBudget: number;
  currency: string;
  guestCount: number;
  durationHours: number;
  locationType: string;
  specialRequirements: string;
}
